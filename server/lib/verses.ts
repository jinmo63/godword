// "빌립보서 4:6-7" → "빌립보서 4:6" (시작 절 기준으로 비교)
export const refKey = (s: string) => s.replace(/-\d+$/, "").trim();
export const verseKey = (v: { book: string; chapter: number; verse_start: number }) =>
  `${v.book} ${v.chapter}:${v.verse_start}`;

export const ALL_KEYS = new Set(Object.values(THEMES).flat().map(refKey));

function shuffle<T>(xs: T[]): T[] {
  const a = [...xs];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// 주제마다 perTheme개씩 무작위로 뽑아 "- 주제: 구절, 구절" 형태의 문자열로
export function samplePool(perTheme = 4): string {
  return shuffle(Object.entries(THEMES))
    .map(([theme, refs]) => `- ${theme}: ${shuffle(refs).slice(0, perTheme).join(", ")}`)
    .join("\n");
}
